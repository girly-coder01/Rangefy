#!/usr/bin/env bash
# Copies ABIs and deployed addresses out of contracts/.
#   frontend/src/config/abis/*.ts, ai-engine/src/chain/abis/*.json
#   frontend/src/config/deployments/<chainId>.json
#   ai-engine/.env.addresses (Unichain Sepolia only)
# Env: CHAIN_ID (default 1301), SKIP_ABIS=1, FORGE_FLAGS
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
CONTRACTS="$ROOT/contracts"
FE_ABIS="$ROOT/frontend/src/config/abis"
AI_ABIS="$ROOT/ai-engine/src/chain/abis"
FE_DEPLOYMENTS="$ROOT/frontend/src/config/deployments"
CHAIN_ID="${CHAIN_ID:-1301}"
NAMES=(RangefyHook SignalOracle RangeVault VaultFactory CuratorRegistry SimpleSwapRouter RangefyLens MockERC20)

command -v jq >/dev/null || { echo "jq is required"; exit 1; }

if [[ "${SKIP_ABIS:-0}" != 1 ]]; then
  echo "→ forge build"
  (cd "$CONTRACTS" && forge build --silent ${FORGE_FLAGS:-})
  mkdir -p "$FE_ABIS" "$AI_ABIS"
  : > "$FE_ABIS/index.ts"
  for n in "${NAMES[@]}"; do
    # pick the artifact compiled from src/ (lib mocks can share a contract name)
    artifact=""
    for f in $(find "$CONTRACTS/out" -path "*/$n.sol/$n.json"); do
      jq -e --arg n "$n" '.metadata.settings.compilationTarget | to_entries[0] | (.key | startswith("src/")) and .value == $n' "$f" >/dev/null 2>&1 && { artifact=$f; break; }
    done
    [[ -z "$artifact" ]] && { echo "  ! $n not found"; continue; }
    jq '.abi' "$artifact" > "$AI_ABIS/$n.json"
    printf '// generated by scripts/sync-abis.sh\nexport const %sAbi = %s as const;\n' "$n" "$(jq '.abi' "$artifact")" > "$FE_ABIS/$n.ts"
    echo "export { ${n}Abi } from \"./$n\";" >> "$FE_ABIS/index.ts"
    echo "  ✓ $n"
  done
fi

BOOK="$CONTRACTS/deployments/$CHAIN_ID"
if [[ ! -f "$BOOK/core.json" ]]; then
  echo "→ no deployments for chain $CHAIN_ID"
  exit 0
fi
get() { jq -r ".$2 // \"\"" "$BOOK/$1.json" 2>/dev/null || true; }

MWETH=$(get tokens mWETH); MUSDC=$(get tokens mUSDC)
if [[ "$(tr 'A-F' 'a-f' <<<"$MWETH")" < "$(tr 'A-F' 'a-f' <<<"$MUSDC")" ]]; then T0=$MWETH; T1=$MUSDC; else T0=$MUSDC; T1=$MWETH; fi

mkdir -p "$FE_DEPLOYMENTS"
jq -n \
  --argjson chainId "$CHAIN_ID" \
  --argjson deployBlock "$(get tokens block)" \
  --arg poolManager "$(get core poolManager)" \
  --arg hook "$(get core hook)" \
  --arg signalOracle "$(get core signalOracle)" \
  --arg vaultFactory "$(get core vaultFactory)" \
  --arg curatorRegistry "$(get core curatorRegistry)" \
  --arg router "$(get core router)" \
  --arg lens "$(get core lens)" \
  --arg mWETH "$MWETH" --arg mUSDC "$MUSDC" \
  '{chainId: $chainId, deployBlock: $deployBlock, poolManager: $poolManager, hook: $hook, signalOracle: $signalOracle,
    vaultFactory: $vaultFactory, curatorRegistry: $curatorRegistry, router: $router, lens: $lens,
    mWETH: $mWETH, mUSDC: $mUSDC}' > "$FE_DEPLOYMENTS/$CHAIN_ID.json"
echo "→ frontend/src/config/deployments/$CHAIN_ID.json"

if [[ "$CHAIN_ID" == 1301 ]]; then
  cat > "$ROOT/ai-engine/.env.addresses" <<ENV
SIGNAL_ORACLE=$(get core signalOracle)
HOOK=$(get core hook)
FACTORY=$(get core vaultFactory)
ROUTER=$(get core router)
LENS=$(get core lens)
TOKEN0=$T0
TOKEN1=$T1
ENV
  echo "→ ai-engine/.env.addresses"
fi
