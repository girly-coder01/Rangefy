#!/usr/bin/env bash
# Full Rangefy stack on anvil.
#   ./scripts/local-stack.sh          fresh chain (31337), deploys its own Uniswap v4
#   FORK=1 ./scripts/local-stack.sh   fork of Unichain Sepolia (31338), uses the canonical v4 contracts
# Writes ai-engine/.env.local and frontend/src/config/deployments/<chainId>.json.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
export PATH="$PATH:$HOME/.foundry/bin"
RPC="${RPC:-http://127.0.0.1:8545}"
FORK_URL="${FORK_URL:-https://sepolia.unichain.org}"
FORGE_FLAGS="${FORGE_FLAGS:-}"
if [[ "${FORK:-0}" == 1 ]]; then CID=31338; else CID=31337; fi

# anvil dev accounts (public test mnemonic)
MNEMONIC="test test test test test test test test test test test junk"
K=(); for i in 0 1 2 3 4 5 6; do K+=("$(cast wallet private-key --mnemonic "$MNEMONIC" --mnemonic-index $i)"); done
addr() { cast wallet address --private-key "$1"; }

if ! cast chain-id --rpc-url "$RPC" >/dev/null 2>&1; then
  echo "→ starting anvil (chain $CID)"
  if [[ $CID == 31338 ]]; then
    anvil --silent --block-time 1 --fork-url "$FORK_URL" --chain-id $CID > /tmp/rangefy-anvil.log 2>&1 &
  else
    anvil --silent --block-time 1 > /tmp/rangefy-anvil.log 2>&1 &
  fi
  echo $! > /tmp/rangefy-anvil.pid
  for _ in $(seq 100); do cast chain-id --rpc-url "$RPC" >/dev/null 2>&1 && break; sleep 0.3; done
fi
[[ "$(cast chain-id --rpc-url "$RPC")" == "$CID" ]] || { echo "RPC at $RPC is not chain $CID"; exit 1; }

cd "$ROOT/contracts"
rm -rf "deployments/$CID"
export PRIVATE_KEY=${K[0]} SIGNAL_UPDATER=$(addr ${K[1]}) KEEPER=$(addr ${K[2]}) MIRROR=$(addr ${K[3]})
export CURATOR_ATLAS_KEY=${K[4]} CURATOR_HARBOR_KEY=${K[5]} CURATOR_VECTOR_KEY=${K[6]}
export ETH_PRICE_USD=${ETH_PRICE_USD:-3000}
run() { echo "→ $1"; forge script "$1" --rpc-url "$RPC" --broadcast --slow $FORGE_FLAGS -q > /dev/null; }

if [[ $CID == 31337 ]]; then
  run script/local/DeployV4Local.s.sol
  export POOL_MANAGER=$(jq -r .poolManager deployments/31337/v4.json)
  export POOL_MODIFY_LIQUIDITY_TEST=$(jq -r .modifyLiquidityTest deployments/31337/v4.json)
fi
run script/00_DeployTokens.s.sol
run script/01_DeployCore.s.sol
run script/02_InitPool.s.sol
run script/03_SeedCurators.s.sol

c() { jq -r ".$2" "deployments/$CID/$1.json"; }
cat > "$ROOT/ai-engine/.env.local" <<ENV
# generated by scripts/local-stack.sh (chain $CID)
RPC_URL=$RPC
CHAIN_ID=$CID
SIGNAL_UPDATER_KEY=${K[1]}
KEEPER_KEY=${K[2]}
MIRROR_KEY=${K[3]}
SIGNAL_ORACLE=$(c core signalOracle)
HOOK=$(c core hook)
FACTORY=$(c core vaultFactory)
ROUTER=$(c core router)
LENS=$(c core lens)
TOKEN0=$(c tokens mWETH)
TOKEN1=$(c tokens mUSDC)
DB_PATH=data/local.db
ENV
CHAIN_ID=$CID SKIP_ABIS=1 "$ROOT/scripts/sync-abis.sh" > /dev/null
echo "✓ stack ready on $CID — vaults: $(jq -c 'del(.block)' deployments/$CID/vaults.json)"
